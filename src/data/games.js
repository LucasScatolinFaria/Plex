export const getGame = (id) => GAMES.find((game) => game.id === id);

// modos "casuais" (ex.: 2 jogadores) não valem estrelas
export const rankedModes = (game) => game.modes.filter((mode) => !mode.casual);

export const maxStars = (game) => rankedModes(game).length * 3;

export const TOTAL_STARS = GAMES.reduce((sum, game) => sum + maxStars(game), 0);
